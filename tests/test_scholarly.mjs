import assert from 'node:assert/strict';
import {analyze,DEFAULTS} from '../web/engine.mjs';
import {freezeProtocol,methodsRecord,sensitivity,academicTable,methodsText} from '../web/scholarly.mjs';
const mapping={id:'id',created:'created',closed:'closed',agency:'agency',service:'service',borough:'borough'};
const rows=[{id:'1',created:'2025-01-01',closed:'2025-01-01',agency:'DSNY',service:'Graffiti',borough:'BRONX'},{id:'2',created:'2025-01-01',closed:'',agency:'DSNY',service:'Graffiti',borough:'QUEENS'}];
const config={...DEFAULTS,minN:1};
const sha='a'.repeat(64);
const state={dataset:{data:rows},mapping,config,sha,synthetic:true};
const frozen=freezeProtocol(state,'Research question?','Descriptive','https://example.org','2026-11-25T00:00:00Z');
assert.throws(()=>freezeProtocol({...state,sha:null},'x','',''));
const report=analyze(rows,mapping,config);report.mapping=mapping;report.source={sha256:sha,synthetic:true};
report.methods=methodsRecord(report,frozen);
assert.equal(report.methods.protocolStatus,'Matches local frozen protocol');
assert.equal(methodsRecord({...report,config:{...config,wFriction:.5}},frozen).frozenProtocol,null);
assert.equal(methodsRecord({...report,mapping:{...mapping,id:'other'}},frozen).frozenProtocol,null);
assert.match(methodsText(report),/SYNTHETIC DEMONSTRATION/);
const s=sensitivity(rows,mapping,report);
assert.equal(s.rows.length,60);
const primary=s.rows.filter(r=>r.primary);
assert.equal(primary.length,2);
for(const r of primary)assert.equal(r.deltaFromPrimary,0);
assert.equal(primary.find(r=>r.borough==='BRONX').signedDifference,-1);
assert.equal(primary.find(r=>r.borough==='QUEENS').signedDifference,1);
assert.ok(s.rows.every(r=>r.score>=0&&r.score<=100));
assert.equal(academicTable(report)[0].synthetic,true);
const small=analyze(rows,mapping,{...config,minN:2});
small.source=report.source;
assert.ok(sensitivity(rows,mapping,small).rows.every(r=>r.score===null));
console.log('PASS: scholarly protocol, methods, sensitivity and synthetic safeguards');
